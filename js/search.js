let selectedCategories = new Set();

function renderCategoryChips() {
    const container = document.getElementById("category-cards");
    if (!container || typeof categories === "undefined") return;

    const extendedCategories = [
        ...categories,
        { id: "info-pages", title: "Info Pages", icon: "ℹ️", description: "Static info sites" }
    ];

    const nonEmpty = extendedCategories.filter(cat => {
        if (cat.id === "info-pages") {
            return staticPages.length > 0;
        }

        const count = typeof recipes !== "undefined"
            ? recipes.filter(r => r.categories && r.categories.includes(cat.id)).length
            : 0;
        return count > 0;
    });

    let chipsHtml = nonEmpty.map(cat => {
        const isActive = selectedCategories.has(cat.id);
        return `<button class="category-chip${isActive ? " active" : ""}" data-cat="${cat.id}">${cat.icon} ${cat.title}</button>`;
    }).join("");

    if (selectedCategories.size > 0) {
        chipsHtml += `<button type="button" id="clear-categories-btn" class="clear-categories-btn">Clear filters</button>`;
    }

    container.innerHTML = chipsHtml;

    container.querySelectorAll(".category-chip").forEach(chip => {
        chip.addEventListener("click", () => {
            const id = chip.dataset.cat;
            selectedCategories.has(id) ? selectedCategories.delete(id) : selectedCategories.add(id);
            renderCategoryChips();
            renderAndFilter();
        });
    });

    const clearCatBtn = document.getElementById("clear-categories-btn");
    if (clearCatBtn) {
        clearCatBtn.addEventListener("click", () => {
            selectedCategories.clear();
            renderCategoryChips();
            renderAndFilter();
        });
    }
}

function updateSearchTitle(searchQuery, hasCategories) {
    const searchTitle = document.getElementById("search-title");
    if (!searchTitle) return;

    if (searchQuery && hasCategories) {
        searchTitle.textContent = `Results for ${searchQuery} (filtered)`;
    } else if (searchQuery) {
        searchTitle.textContent = `Search results for ${searchQuery}`;
    } else if (hasCategories) {
        searchTitle.textContent = "Recipes in selected categories";
    } else {
        searchTitle.textContent = "No search term entered";
    }
}

function renderAndFilter() {
    const urlParams = new URLSearchParams(window.location.search);
    const searchQuery = (urlParams.get("q") || "").trim();
    const lowerQuery = searchQuery.toLowerCase();
    const hasCategories = selectedCategories.size > 0;

    updateSearchTitle(searchQuery, hasCategories);

    if (!searchQuery && !hasCategories) {
        const recipesList = document.getElementById("recipes-list");
        if (recipesList) recipesList.innerHTML = "";
        return;
    }

    const allRecipes = typeof recipes !== "undefined" ? recipes : [];
    const allContent = [...allRecipes, ...staticPages];

    const results = allContent.filter(item => {
        const textMatch = !lowerQuery ||
            item.title.toLowerCase().includes(lowerQuery) ||
            (item.description && item.description.toLowerCase().includes(lowerQuery)) ||
            (item.content && item.content.toLowerCase().includes(lowerQuery)) ||
            (item.ingredients && item.ingredients.some(ing => ing.toLowerCase().includes(lowerQuery)));

        const catMatch = !hasCategories || (
            (selectedCategories.has("info-pages") && item.isPage) ||
            (!item.isPage && item.categories && item.categories.some(c => selectedCategories.has(c)))
        );

        return textMatch && catMatch;
    });

    renderSearchResults(results);
}

function renderSearchResults(resultsToRender) {
    const recipesList = document.getElementById("recipes-list");
    if (!recipesList) return;
    recipesList.innerHTML = "";

    if (resultsToRender.length === 0) {
        recipesList.innerHTML = `<p class="no-results">No results matched your search.</p>`;
        return;
    }

    resultsToRender.forEach((item) => {
        const card = document.createElement("article");
        card.classList.add("recipe-card");

        const targetUrl = item.isPage ? item.id : `../recipes/recipe-detail.html?id=${item.id}`;
        const buttonText = item.isPage ? "Open Page" : "View recipe";

        card.innerHTML = `
            ${!item.isPage ? `
                <img src="${item.image}" alt="${item.title}">
            ` : `
                <div class="search-page-banner">
                    <span>ℹ️ Info Page</span>
                </div>
            `}
            <div class="recipe-card-content">
                <h2>${item.title}</h2>
                <p>${item.description}</p>
                ${!item.isPage ? `
                <div class="recipe-meta">
                    <span>${item.time}</span>
                    <span>${item.difficulty}</span>
                </div>` : ""}
                <a href="${targetUrl}" class="btn">${buttonText}</a>
            </div>
        `;
        recipesList.appendChild(card);
    });
}

function resetSearch(categoryId) {
    const searchInput = document.getElementById("search");
    const searchPageInput = document.getElementById("search-page-input");
    selectedCategories.add(categoryId);

    const cleanUrl = new URL(window.location.href);
    cleanUrl.searchParams.delete("q");

    history.replaceState({}, "", cleanUrl.toString());

    if (searchInput) searchInput.value = "";
    if (searchPageInput) searchPageInput.value = "";

    renderCategoryChips();
    renderAndFilter();
}

document.addEventListener("DOMContentLoaded", () => {
    const searchInput = document.getElementById("search");
    const searchPageInput = document.getElementById("search-page-input");
    const urlParams = new URLSearchParams(window.location.search);
    const searchQuery = urlParams.get("q");

    renderCategoryChips();

    if (!searchQuery) {
        updateSearchTitle("", false);
        if (searchPageInput) searchPageInput.focus();
        return;
    }

    const cleanQuery = searchQuery.trim();

    const matchedCategory = typeof categories !== "undefined"
        ? categories.find(cat => {
            const title = cat.title.toLowerCase();
            const query = cleanQuery.toLowerCase();
            return title === query || title.includes(query) && query.length >= 3;
        })
        : null;

    const matchedInfoPage = cleanQuery.toLowerCase().includes("info") || cleanQuery.toLowerCase().includes("page");

    if (matchedInfoPage) {
        resetSearch("info-pages");
        return;
    }

    if (matchedCategory) {
        resetSearch(matchedCategory.id);
        return;
    }

    if (searchInput) searchInput.value = cleanQuery;
    if (searchPageInput) searchPageInput.value = cleanQuery;

    renderAndFilter();

    const clearBtn = document.getElementById("clear-search-btn");

    if (clearBtn) {
        clearBtn.addEventListener("click", () => {
            const searchInput = document.getElementById("search");
            const searchPageInput = document.getElementById("search-page-input");
            if (searchInput) searchInput.value = "";
            if (searchPageInput) searchPageInput.value = "";

            const cleanUrl = new URL(window.location.href);
            cleanUrl.searchParams.delete("q");

            history.replaceState({}, "", cleanUrl.toString());
            
            renderAndFilter();
        });
    }
});
